import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createRifleModel } from '../app/src/main/assets/game/js/rifle-model.js';
import { createRifleEffects } from '../app/src/main/assets/game/js/rifle-effects.js';

test('disparo mantém os efeitos até o fim de suas durações e retorna o recuo exponencialmente', () => {
  const scene = new THREE.Scene();
  const rifle = createRifleModel(THREE);
  scene.add(rifle.root);
  const effects = createRifleEffects({ THREE, scene, recoilGroup: rifle.recoilGroup, muzzle: rifle.muzzle });
  effects.pulseShot(new THREE.Vector3(0, 1, -10));
  assert.equal(effects.flash.visible, true);
  assert.equal(effects.flash.material.emissive.getHex(), 0xff7a16);
  assert.equal(effects.flash.material.emissiveIntensity, 3);
  assert.equal(rifle.recoilGroup.position.z, 0.08);
  const tracer = scene.children.find((child) => child.isLine);
  assert.ok(tracer);
  assert.equal(tracer.material.color.getHex(), 0xffb24a);
  effects.update(0.01);
  assert.equal(effects.flash.visible, true);
  assert.ok(scene.children.includes(tracer));
  assert.ok(Math.abs(rifle.recoilGroup.position.z - (0.08 * Math.exp(-1.2))) < 1e-12);
  effects.update(0.034);
  assert.equal(effects.flash.visible, true);
  assert.ok(scene.children.includes(tracer));
  effects.update(0.002);
  assert.equal(effects.flash.visible, false);
  assert.ok(scene.children.includes(tracer));
  effects.update(0.018);
  assert.ok(scene.children.includes(tracer));
  effects.update(0.002);
  assert.equal(scene.children.includes(tracer), false);
  assert.ok(Math.abs(rifle.recoilGroup.position.z) < 0.001);
  effects.dispose();
  rifle.dispose();
});

test('dispose libera traço temporário uma vez e permanece idempotente', () => {
  const scene = new THREE.Scene();
  const rifle = createRifleModel(THREE);
  scene.add(rifle.root);
  const effects = createRifleEffects({ THREE, scene, recoilGroup: rifle.recoilGroup, muzzle: rifle.muzzle });
  effects.pulseShot(new THREE.Vector3(0, 1, -10));
  const tracer = scene.children.find((child) => child.isLine);
  let geometryDisposals = 0;
  let materialDisposals = 0;
  const disposeGeometry = tracer.geometry.dispose.bind(tracer.geometry);
  const disposeMaterial = tracer.material.dispose.bind(tracer.material);
  tracer.geometry.dispose = () => { geometryDisposals += 1; disposeGeometry(); };
  tracer.material.dispose = () => { materialDisposals += 1; disposeMaterial(); };
  effects.dispose();
  effects.dispose();
  assert.equal(scene.children.includes(tracer), false);
  assert.equal(geometryDisposals, 1);
  assert.equal(materialDisposals, 1);
  assert.equal(rifle.recoilGroup.position.z, 0);
  rifle.dispose();
});
